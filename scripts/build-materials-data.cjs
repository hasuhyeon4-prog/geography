/* Project pinned datasets -> the small browser input for 자료형 연습. No network. */
'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const root=path.resolve(__dirname,'..'),sources={};
function read(file){const b=fs.readFileSync(path.join(root,file));sources[file]=crypto.createHash('sha256').update(b).digest('hex');return JSON.parse(b);}
const normal=read('data/climate-normals.json'),extra=read('data/climate-normals-extension.json');
const sites={};
for(const s of [...normal.sites,...extra.sites]){
 if(!s.usage?.climateGraph||!s.temperatureC?.every(Number.isFinite)||!s.precipitationMm?.every(Number.isFinite))continue;
 if(s.temperatureC.length!==12||s.precipitationMm.length!==12)continue;
 sites[s.name]={name:s.name,lat:s.station.latitude,lon:s.station.longitude,t:s.temperatureC,p:s.precipitationMm,period:s.normalPeriod,station:s.station.name,source:s.sourceId||s.sourceFile};
}
const pop=read('data/country-indicators.json'),eco=read('data/economy-indicators.json'),wup=read('data/urbanization-change.json');
const names=['일본','인도','니제르','차드','튀르키예','미국','브라질','영국','파키스탄','말레이시아','탄자니아','독일','프랑스','이집트','카자흐스탄','사우디아라비아'];
const countries={};
for(const name of names){
 const p=pop.countries[name],e=eco.countries[name];if(!p)continue;
 countries[name]={values:p.values,series:p.series,economy:e?.values||{},economySeries:e?.series||{}};
}
const urban={};
for(const name of [...names,'아시아','아프리카','유럽','라틴 아메리카','앵글로아메리카']){
 const area=wup.areas[name];if(!area)continue;
 urban[name]={};
 for(const year of ['1950','1960','1970','2010','2015','2020']){
  const s=area.series;const u=s.urbanPopulation[year],r=s.ruralPopulation[year];
  if(!Number.isFinite(u)||!Number.isFinite(r))continue;
  // Display and solve from the same integer thousand-person values.
  urban[name][year]={u:Math.round(u/1000),r:Math.round(r/1000)};
 }
}
const loc=read('data/extension-sources/location-items.json'),cities={};
for(const name of ['마닐라','도쿄','웰링턴','홍콩','카슈가르','오클랜드','뉴욕','보스턴','샌프란시스코','로스앤젤레스','시카고','휴스턴']){
 const item=loc.find(x=>x.name===name&&x.geometry.type==='point');
 if(item)cities[name]={lat:item.geometry.lat,lon:item.geometry.lon};
}
const migrant=read('data/us-migrants-by-origin.json'),migrants={};
for(const name of ['멕시코','인도','독일','세네갈']){const x=migrant.countries[name];if(x?.bothSexes?.['2020']!=null)migrants[name]=x.bothSexes['2020'];}
const goalSpec=read('data/lecture-gap-goals.json'),given=read('data/materials-given.json'),energy=read('data/energy-change-source.json');
const shapes=require('../assets/country-boundaries.js'),kb=require('../assets/entity-kb.js'),maps={};
for(const file of ['assets/country-boundaries.js','assets/entity-kb.js'])sources[file]=crypto.createHash('sha256').update(fs.readFileSync(root+'/'+file)).digest('hex');
const mapNames=new Set([...given.medical.rows,...given.ai.rows,...given.topTwo.rows].map(r=>r[0]).concat(['미얀마','베트남','중국','인도','말레이시아','싱가포르']));
for(const name of mapNames){if(shapes.byName[name]&&kb.entities[name])maps[name]={polygons:shapes.byName[name].polygons,label:kb.entities[name].label};}
const continuation=read('data/goal-continuation-source.json');
const religionSource=read('data/religion-composition.json'),religions={};
for(const name of ['방글라데시','스리랑카','필리핀','미얀마'])religions[name]=religionSource.countries[name];
const agricultureSource=read('data/agriculture.json'),agriculture={};
for(const name of ['프랑스','독일','인도']){
 const code=agricultureSource.entities[name].areaCodes[0],s=agricultureSource.seriesByArea[code];
 agriculture[name]={};
 for(const field of ['qcl-area:밀','qcl-production:밀','qcl-yield:밀','fbs-production:곡물 전체','fbs-imports:곡물 전체','fbs-exports:곡물 전체','fbs-stockVariation:곡물 전체','fbs-domesticSupply:곡물 전체']){
  if(Number.isFinite(s[field]?.['2023']))agriculture[name][field]=s[field]['2023'];
 }
}
const data={version:2,sources,climate:{period:normal.normalPeriod,sites},countries,urban,cities,migrants,given,maps,energy,continuation,religions,agriculture,migrantSource:{source:migrant.source,year:'2020',definition:migrant.definition,practice:'suppliedData'},goals:goalSpec.map(g=>({id:g.id,group:g.group,goal:g.goal,venue:g.venue}))};
const text='/* Generated by scripts/build-materials-data.cjs. */\n(function(r,d){if(typeof module==="object"&&module.exports)module.exports=d;else r.WGMaterialsData=d})(typeof globalThis!=="undefined"?globalThis:this,'+JSON.stringify(data)+');\n';
const file=path.join(root,'assets/materials-data.js');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==text)throw Error('materials-data.js is stale');}
else fs.writeFileSync(file,text);
console.log('자료형 입력',Object.keys(sites).length,'관측소',Object.keys(urban).length,'인구 지역',Object.keys(cities).length,'도시');
