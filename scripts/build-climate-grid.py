#!/usr/bin/env python3
"""Build assets/climate-grid.js: a 0.5° world grid of the lecture's 14 climate types.

Sources (not committed; pass their paths):
  * Beck et al. (2023) Köppen-Geiger 1991–2020, 0.5°, CC BY 4.0
    https://doi.org/10.6084/m9.figshare.21789074 (koppen_geiger_tif.zip → 1991_2020/koppen_geiger_0p5.tif)
  * NOAA ETOPO5 5-minute relief, public domain
    https://www.ngdc.noaa.gov/mgg/global/relief/ETOPO5/TOPO/ETOPO5/ETOPO5.DAT

Usage: python3 -I scripts/build-climate-grid.py KOPPEN_0P5_TIF ETOPO5_DAT [--check]

The grid keeps the Köppen-Geiger class of every land cell and its mean elevation; the page derives the
lecture type (Ds → Df, Csc → Cs, Cfc → Cfb, Cwc → Cw) and the highland rule from them, so the
rule lives in one place (assets/climate-paint.js).
"""
import hashlib, json, sys
import numpy as np
from PIL import Image

ROWS, COLS = 360, 720  # 0.5°, rows from 90°N, columns from 180°W


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def rle(values):
    """Run-length pairs [value, count, value, count, ...] over the whole grid in row order."""
    out, prev, n = [], None, 0
    for v in values:
        if v == prev:
            n += 1
        else:
            if prev is not None:
                out += [prev, n]
            prev, n = v, 1
    out += [prev, n]
    return out


def main(argv):
    check = '--check' in argv
    tif, dat = [a for a in argv if not a.startswith('--')][:2]
    kg = np.array(Image.open(tif)).astype(np.int16)
    if kg.shape != (ROWS, COLS):
        raise SystemExit('unexpected Köppen grid %r' % (kg.shape,))
    topo = np.fromfile(dat, dtype='>i2').reshape(2160, 4320)  # 5', rows from 90°N, columns from 0°E
    # ETOPO5 columns start at 0°E; roll so they start at 180°W, then average 6×6 blocks into 0.5° cells.
    topo = np.roll(topo, 2160, axis=1).astype(np.float64)
    # Mean over the land pixels only, so a coastal cell is not pulled below sea level by the sea floor.
    blocks = topo.reshape(ROWS, 6, COLS, 6)
    dry = blocks >= 0
    count = dry.sum(axis=(1, 3))
    elev = np.where(count > 0, np.where(dry, blocks, 0).sum(axis=(1, 3)) / np.maximum(count, 1), 0)
    land = kg > 0
    # Elevation in 100 m steps for land cells (ocean 0); negative land (Caspian, Dead Sea) is 0.
    elev100 = np.where(land, np.clip(np.round(elev / 100.0), 0, 80), 0).astype(int)
    data = {
        'rows': ROWS, 'cols': COLS, 'cell': 0.5, 'west': -180, 'north': 90,
        'period': '1991–2020',
        'source': 'Beck et al. (2023) High-resolution (1 km) Köppen-Geiger maps for 1901–2099, Scientific Data 10, 724 — 0.5° map, CC BY 4.0',
        'sourceUrl': 'https://doi.org/10.6084/m9.figshare.21789074',
        'sourceSha256': sha(tif),
        'elevationSource': 'NOAA ETOPO5 5-minute global relief (public domain), land pixels averaged to 0.5°',
        'elevationUrl': 'https://www.ngdc.noaa.gov/mgg/global/relief/ETOPO5/TOPO/ETOPO5/ETOPO5.DAT',
        'elevationSha256': sha(dat),
        'koppen': rle(kg.flatten().tolist()),
        'elev100': rle(elev100.flatten().tolist()),
    }
    text = ('/* Generated by scripts/build-climate-grid.py: Köppen-Geiger class (1–30, 0 = sea) and mean elevation (100 m) per 0.5° cell. */\n'
            '(function(r,d){if(typeof module==="object"&&module.exports)module.exports=d;else r.WGClimateGrid=d;})'
            '(typeof globalThis!=="undefined"?globalThis:this,' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ');\n')
    out = 'assets/climate-grid.js'
    if check:
        if open(out, encoding='utf-8').read() != text:
            raise SystemExit('climate-grid.js is stale')
    else:
        open(out, 'w', encoding='utf-8').write(text)
    print('land cells', int(land.sum()), 'bytes', len(text.encode('utf-8')))


if __name__ == '__main__':
    main(sys.argv[1:])
