/* Build assets/table-facts.js: every lecture-table cell asked as one O/X statement (2026-10-29).
 * "{row}의 「{column}」: {cell}" is true with the row's own cell, false with another row's
 * different cell in the same column. Truth is fixed by a hash of the id, so a statement keeps
 * its answer across builds. Cells naming a row of the table are left out, since the name
 * would give the answer away. Usage: node scripts/build-table-facts.cjs [--check] */
'use strict';
const fs=require('fs'),path=require('path'),crypto=require('crypto'),root=path.resolve(__dirname,'..');
const T=require('../assets/concept-tables.js'),G=require('../assets/goal-tables.js').create(require('../assets/goal-tables-data.js'));
const names=['위치·방위','지도·지리 정보','기후','지형','문화·종교','인구·도시','농목업','에너지·자원','공업·무역','환경','지역지리','자료 해석'];
const section={};for(const d of T.domains.concat(G.domains))section[d.id]=d.section;
const topics=names.map((n,i)=>({id:'table-p'+String(i).padStart(2,'0'),name:'강의 표 · '+n}));
const hash=s=>crypto.createHash('sha256').update(s).digest();
const items=[];
function add(t,columns){
 // A row's name or any part of it that names it (t.tokens: 메카 of 메카·메디나) gives the answer away.
 const named=(t.tokens||t.rows.map(r=>[r])).flat().filter(x=>x.length>=2);
 const leaks=cell=>named.some(r=>cell.includes(r));
 for(const c of columns)t.rows.forEach((row,i)=>{
  const cell=c.cells[i];if(!cell||leaks(cell))return;
  const others=[...new Set(c.cells.filter((v,j)=>j!==i&&v&&v!==cell&&!leaks(v)))];if(!others.length)return;
  const id='table|'+t.id+'|'+row+'|'+c.label,h=hash(id),truth=h[0]%2===0,shown=truth?cell:others[h[1]%others.length];
  const sec=section[t.domain]||'P00',topic='table-'+sec.toLowerCase();
  items.push({id,topic,claim:row+'의 「'+c.label+'」: '+shown,answer:truth,explain:'바른 서술: '+row+'의 「'+c.label+'」 — '+cell,source:'강의 표 '+t.block,period:'개념',practice:'recall',revision:1,auditStatus:'table-generated',table:t.id});
 });
}
for(const t of T.tables)if(!t.studyOnly)add(t,t.columns.filter(c=>c.askable));
for(const t of G.tables)add(t,t.columns.filter(c=>!t.skipQuizColumns.includes(c.label)));
const ids=new Set();for(const q of items){if(ids.has(q.id))throw Error('duplicate '+q.id);ids.add(q.id);}
const used=new Set(items.map(q=>q.topic)),data={topics:topics.filter(t=>used.has(t.id)),items};
const text='/* Generated by scripts/build-table-facts.cjs. */\n(function(r,a){if(typeof module==="object"&&module.exports)module.exports=a;else{r.WGTableFacts=a;var f=r.WGFacts;if(!f)return;var ids=new Set(f.items.map(function(q){return q.id}));a.topics.forEach(function(t){if(!f.topics.some(function(x){return x.id===t.id}))f.topics.push(t)});a.items.forEach(function(q){if(!ids.has(q.id)){f.items.push(q);ids.add(q.id)}})}})(typeof globalThis!=="undefined"?globalThis:this,'+JSON.stringify(data)+');\n';
const file=path.join(root,'assets/table-facts.js');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==text)throw Error('table-facts.js is stale');}else fs.writeFileSync(file,text);
console.log('강의 표 OX',items.length,'참',items.filter(q=>q.answer).length,'주제',data.topics.length);
