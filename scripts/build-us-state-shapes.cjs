#!/usr/bin/env node
// Packs data/us-state-boundaries.geojson (Natural Earth 1:50m admin-1, public domain) into
// assets/us-state-boundaries.js for the exam map, in the encoding of assets/country-boundaries.js.
// Keys are the state names of data/us-state-manufacturing-series.json.
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const read = p => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const geo = read('data/us-state-boundaries.geojson'), states = read('data/us-state-manufacturing-series.json').states;
function packRing(ring) {
  let out = '', prior = [0, 0];
  for (const pt of ring) for (let k = 0; k < 2; k++) {
    const v = Math.round(pt[k] * 1e5), d = v - prior[k];
    prior[k] = v;
    let n = d < 0 ? ~(d << 1) : d << 1;
    while (n >= 32) { out += String.fromCharCode(((n & 31) | 32) + 63); n >>>= 5; }
    out += String.fromCharCode(n + 63);
  }
  return out;
}
const byName = {};
for (const st of Object.values(states)) {
  const f = geo.features.find(x => x.properties.name_en === st.sourceName);
  if (!f) throw new Error('no boundary for ' + st.sourceName);
  const polys = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates];
  byName[st.name] = {code: f.properties.postal, polygons: polys.map(p => p.map(packRing))};
}
const payload = JSON.stringify({source: geo.source, byName});
fs.writeFileSync(path.join(ROOT, 'assets/us-state-boundaries.js'), '/* Natural Earth public-domain state boundaries; generated by scripts/build-us-state-shapes.cjs. */\n' +
  '(function(r){var d=' + payload + ';function ring(s){var p=[],v=[0,0],i=0;while(i<s.length){for(var k=0;k<2;k++){var n=0,b,t=0;do{b=s.charCodeAt(i++)-63;n|=(b&31)<<t;t+=5;}while(b>=32);v[k]+=(n&1)?~(n>>>1):n>>>1;}p.push([v[0]/1e5,v[1]/1e5]);}return p;}' +
  'Object.keys(d.byName).forEach(function(n){d.byName[n].polygons=d.byName[n].polygons.map(function(p){return p.map(ring);});});if(typeof module==="object"&&module.exports)module.exports=d;else r.WGStateShapes=d;})(typeof globalThis!=="undefined"?globalThis:this);\n');
console.log(JSON.stringify({states: Object.keys(byName).length, bytes: payload.length}));
