'use strict';
const fs=require('fs'),path=require('path'),root=path.resolve(__dirname,'..');
const d=JSON.parse(fs.readFileSync(root+'/data/lecture-goal-table-overrides.json','utf8'));
const goals=JSON.parse(fs.readFileSync(root+'/data/lecture-gap-goals.json','utf8'));
for(const t of d.tables){
 if(!t.rows.length||!t.rows.every(r=>r.length===t.headers.length))throw Error(t.id+' invalid rectangle');
 if(new Set(t.rows.map(r=>r[0])).size!==t.rows.length)throw Error(t.id+' duplicate row');
 for(const id of t.goalIds)if(!goals.some(g=>g.id===id&&(g.venue==='강의 표'||id==='G106-1')))throw Error(id);
}
for(const q of d.questions||[]){
 if(!d.tables.some(t=>t.id===q.table)||!q.options[q.answer]||q.options.length<2||q.options.length>5||new Set(q.options).size!==q.options.length)throw Error(q.id+' invalid question');
 for(const id of q.goalIds)if(!goals.some(g=>g.id===id))throw Error(id);
}
const text='/* Generated by scripts/build-goal-tables.cjs. */\n(function(r,d){if(typeof module==="object"&&module.exports)module.exports=d;else r.WGGoalTableData=d})(typeof globalThis!=="undefined"?globalThis:this,'+JSON.stringify(d)+');\n';
const target=root+'/assets/goal-tables-data.js';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==text)throw Error('goal-tables-data.js is stale');}else fs.writeFileSync(target,text);
console.log('재구성 비교표',d.tables.length);
